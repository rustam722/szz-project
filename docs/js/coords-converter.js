'use strict';

// ──────────────────────────────────────────────
// Эллипсоиды
// ──────────────────────────────────────────────
const _EL = {
  WGS84: { a: 6378137.0,  f: 1/298.257223563 },
  KRASS: { a: 6378245.0,  f: 1/298.3 },
};
function _e2(el) { return 2*el.f - el.f*el.f; }

// ──────────────────────────────────────────────
// Datum: WGS-84 ↔ Пулково-1942 (3-param Molodensky)
// ──────────────────────────────────────────────
const _DX = 25, _DY = -141, _DZ = -79;

function _datumShift(lat_r, lon_r, el_from, el_to, dx, dy, dz) {
  const e2 = _e2(el_from);
  const N = el_from.a / Math.sqrt(1 - e2 * Math.sin(lat_r)**2);
  const X = N * Math.cos(lat_r) * Math.cos(lon_r);
  const Y = N * Math.cos(lat_r) * Math.sin(lon_r);
  const Z = N * (1 - e2) * Math.sin(lat_r);
  const X2=X+dx, Y2=Y+dy, Z2=Z+dz;
  const e2b = _e2(el_to);
  const lon2 = Math.atan2(Y2, X2);
  const p = Math.hypot(X2, Y2);
  let lat2 = Math.atan2(Z2, p*(1-e2b));
  for (let i=0; i<12; i++) {
    const N2 = el_to.a / Math.sqrt(1 - e2b*Math.sin(lat2)**2);
    lat2 = Math.atan2(Z2 + e2b*N2*Math.sin(lat2), p);
  }
  return { lat: lat2*180/Math.PI, lon: lon2*180/Math.PI };
}
const _wgsToSk42 = (lat,lon) => _datumShift(lat*Math.PI/180, lon*Math.PI/180, _EL.WGS84, _EL.KRASS,  _DX,  _DY,  _DZ);
const _sk42ToWgs = (lat,lon) => _datumShift(lat*Math.PI/180, lon*Math.PI/180, _EL.KRASS, _EL.WGS84, -_DX, -_DY, -_DZ);

// ──────────────────────────────────────────────
// Дуга меридиана (Красовский или WGS-84)
// ──────────────────────────────────────────────
function _meridianArc(lat_r, el) {
  const e2=_e2(el), e4=e2**2, e6=e2**3;
  return el.a * (
    (1 - e2/4 - 3*e4/64 - 5*e6/256)*lat_r
    - (3*e2/8 + 3*e4/32 + 45*e6/1024)*Math.sin(2*lat_r)
    + (15*e4/256 + 45*e6/1024)*Math.sin(4*lat_r)
    - (35*e6/3072)*Math.sin(6*lat_r)
  );
}

// ──────────────────────────────────────────────
// Гаусс-Крюгер с ЯВНЫМ меридианом (для МСК и СК-42)
// ──────────────────────────────────────────────
function _gkFwdAt(lat_d, lon_d, lon0_d, fe, fn, el) {
  const e2=_e2(el);
  const dL=(lon_d - lon0_d)*Math.PI/180;
  const lat=lat_d*Math.PI/180;
  const sinL=Math.sin(lat), cosL=Math.cos(lat);
  const N=el.a/Math.sqrt(1-e2*sinL**2);
  const eta2=(e2/(1-e2))*cosL**2;
  const t=Math.tan(lat);
  const M=_meridianArc(lat, el);
  const L2=dL**2, L3=dL**3, L4=dL**4, L5=dL**5, L6=dL**6;
  const Xn = M
    + N*sinL*cosL/2*L2
    + N*sinL*cosL**3/24*(5-t**2+9*eta2+4*eta2**2)*L4
    + N*sinL*cosL**5/720*(61-58*t**2+t**4)*L6;
  const Ye_raw = N*cosL*dL
    + N*cosL**3/6*(1-t**2+eta2)*L3
    + N*cosL**5/120*(5-18*t**2+t**4+14*eta2-58*t**2*eta2)*L5;
  return { Xn: Math.round((Xn+fn)*1000)/1000, Ye: Math.round((Ye_raw+fe)*1000)/1000 };
}

function _gkInvAt(Xn, Ye, lon0_d, fe, fn, el) {
  const e2=_e2(el), e4=e2**2, e6=e2**3;
  const x = Xn - fn;   // northing от экватора
  const y0 = Ye - fe;  // easting от осевого меридиана
  if (x < 2000000 || x > 9000000) return null; // ~18°N–82°N — грубый фильтр
  const e1=(1-Math.sqrt(1-e2))/(1+Math.sqrt(1-e2));
  const e12=e1**2, e13=e1**3, e14=e1**4;
  const mu=x/(el.a*(1-e2/4-3*e4/64-5*e6/256));
  const latFP = mu
    + (3*e1/2-27*e13/32)*Math.sin(2*mu)
    + (21*e12/16-55*e14/32)*Math.sin(4*mu)
    + (151*e13/96)*Math.sin(6*mu)
    + (1097*e14/512)*Math.sin(8*mu);
  const sinFP=Math.sin(latFP), cosFP=Math.cos(latFP);
  const N=el.a/Math.sqrt(1-e2*sinFP**2);
  const R=el.a*(1-e2)/(1-e2*sinFP**2)**1.5;
  const ep2=(e2/(1-e2))*cosFP**2;
  const D=y0/N, t=Math.tan(latFP);
  const lat = latFP - (N*t/R)*(
    D**2/2
    -(5+3*t**2+10*ep2-4*ep2**2-9*(e2/(1-e2)))*D**4/24
    +(61+90*t**2+298*ep2+45*t**4-252*(e2/(1-e2))-3*ep2**2)*D**6/720
  );
  const lon = lon0_d*Math.PI/180 + (
    D-(1+2*t**2+ep2)*D**3/6
    +(5-2*ep2+28*t**2-3*ep2**2+8*(e2/(1-e2))+24*t**4)*D**5/120
  )/cosFP;
  return { lat: lat*180/Math.PI, lon: lon*180/Math.PI };
}

// ──────────────────────────────────────────────
// СК-42 Гаусс-Крюгер 6° зоны (стандартный)
// ──────────────────────────────────────────────
function _gkForward(lat_d, lon_d) {
  const zone = Math.floor((lon_d+3)/6)+1;
  const res = _gkFwdAt(lat_d, lon_d, zone*6-3, zone*1e6+500000, 0, _EL.KRASS);
  return { Xn: res.Xn, Ye: res.Ye, zone };
}
function _gkInverse(Xn, Ye) {
  const zone = Math.floor(Ye/1e6);
  if (zone<1||zone>60) return null;
  return _gkInvAt(Xn, Ye, zone*6-3, zone*1e6+500000, 0, _EL.KRASS);
}

