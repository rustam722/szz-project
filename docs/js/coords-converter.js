function _parseCoords(raw) {
  const t = raw.trim().replace(/\r?\n/g,' ').replace(/\s+/g,' ');

  // Geohash
  if (/^[0-9bcdefghjkmnpqrstuvwxyz]{4,12}$/i.test(t)) {
    const ll=_fromGeohash(t); if(ll&&Math.abs(ll.lat)<=90) return{...ll,_src:'Geohash'};
  }

  // MGRS: 37U DB 13250 77000
  const mgrs=t.match(/^(\d{1,2})\s*([A-Z])\s*([A-HJ-NP-Z]{2})\s*(\d{1,5})\s*(\d{1,5})$/i);
  if(mgrs){
    const zone=parseInt(mgrs[1]),band=mgrs[2],colL=mgrs[3][0].toUpperCase(),rowL=mgrs[3][1].toUpperCase();
    const eLocal=parseInt(mgrs[4].padEnd(5,'0')),nLocal=parseInt(mgrs[5].padEnd(5,'0'));
    const colSet=((zone-1)%3)*8,colIdx=_MGRS_COL.indexOf(colL)-colSet;
    const rowOffset=zone%2===0?5:0,rowBase=(_MGRS_ROW.indexOf(rowL)-rowOffset+20)%20;
    const easting=(colIdx+1)*100000+eLocal;
    const bandIdx=_UTMBANDS.indexOf(band.toUpperCase());
    const estNorthing=(bandIdx+1)*888000;
    const nFull=(Math.floor(estNorthing/100000/20)*20+rowBase)*100000+nLocal;
    const ll=_utmInverse(zone,band,easting,nFull);
    if(ll) return{...ll,_src:'MGRS'};
  }

  // UTM: 37U 413250 6177000
  const utm=t.match(/^(\d{1,2})\s*([A-Z])\s+(\d{5,7}(?:[.,]\d+)?)\s+(\d{5,8}(?:[.,]\d+)?)$/i);
  if(utm){const ll=_utmInverse(parseInt(utm[1]),utm[2],parseFloat(utm[3].replace(',','.')),parseFloat(utm[4].replace(',','.')));if(ll)return{...ll,_src:'UTM'};}

  // СК-42 ГК или МСК: два числа
  const twoNum=t.match(/^(\d{4,9}(?:[.,]\d+)?)\s+(\d{4,9}(?:[.,]\d+)?)$/);
  if(twoNum){
    let a=parseFloat(twoNum[1].replace(',','.')), b=parseFloat(twoNum[2].replace(',','.'));
    // Определяем что есть X(northing) и Y(easting с зоной)
    let X=a, Y=b;
    if(Math.floor(b/1e6)>=1 && Math.floor(a/1e6)<1){ X=a; Y=b; }
    else if(Math.floor(a/1e6)>=1 && Math.floor(b/1e6)<1){ X=b; Y=a; }
    // Диапазон Y для МСК: 1_000_000 – 9_999_999 (зоны 1–9, fe 1250000-9250000)
    // Диапазон Y для СК-42 6°: 4_000_000 – 60_000_000
    const zonePrefix = Math.floor(Y / 1e6);

    // МСК: зона 1–9 с false_easting 1250000/2250000/3250000/4250000/5250000
    if(zonePrefix >= 1 && zonePrefix <= 9 && X < 1000000) {
      const candidates = _tryMSK(X, Y);
      if(candidates.length === 1) return candidates[0];
      if(candidates.length > 1) {
        // Несколько совпадений — вернём первое, сохраним все для UI
        const best = candidates[0];
        best._mskCandidates = candidates;
        return best;
      }
      // МСК не найдена — пробуем как стандартный ГК
    }

    // СК-42 6° ГК (зоны 4–32 для России)
    if(zonePrefix >= 4 && zonePrefix <= 32){
      const sk42=_gkInverse(X, Y);
      if(sk42){
        const wgs=_sk42ToWgs(sk42.lat, sk42.lon);
        if(wgs.lat>=41&&wgs.lat<=82&&wgs.lon>=19&&wgs.lon<=192) return{...wgs,_src:'СК-42 ГК',_gkX:X,_gkY:Y};
        // Не в России — пробуем МСК
        const mskFallback=_tryMSK(X, Y);
        if(mskFallback.length>0){const b=mskFallback[0];if(mskFallback.length>1)b._mskCandidates=mskFallback;return b;}
      }
    }

    // WGS-84 (маленькие числа)
    if(Math.abs(a)<=90 && Math.abs(b)<=180) return{lat:a,lon:b,_src:'WGS-84 ГГ'};
    if(Math.abs(b)<=90 && Math.abs(a)<=180) return{lat:b,lon:a,_src:'WGS-84 ГГ'};
  }

  // ГМС: 55°45'21.6"N 37°37'02.4"E
  const dms=t.match(/(\d{1,3})[°\s]+(\d{1,2})[''\s]+(\d{1,2}(?:[.,]\d+)?)[""\s]*([NSns])\s+(\d{1,3})[°\s]+(\d{1,2})[''\s]+(\d{1,2}(?:[.,]\d+)?)[""\s]*([EWew])/);
  if(dms){let lat=parseInt(dms[1])+parseInt(dms[2])/60+parseFloat(dms[3].replace(',','.'))/3600,lon=parseInt(dms[5])+parseInt(dms[6])/60+parseFloat(dms[7].replace(',','.'))/3600;if(/[Ss]/.test(dms[4]))lat=-lat;if(/[Ww]/.test(dms[8]))lon=-lon;if(Math.abs(lat)<=90&&Math.abs(lon)<=180)return{lat,lon,_src:'WGS-84 ГМС'};}
  const dms2=t.match(/([NSns])\s*(\d{1,3})[°\s]+(\d{1,2})[''\s]+(\d{1,2}(?:[.,]\d+)?)[""\s]*\s+([EWew])\s*(\d{1,3})[°\s]+(\d{1,2})[''\s]+(\d{1,2}(?:[.,]\d+)?)[""\s]*/);
  if(dms2){let lat=parseInt(dms2[2])+parseInt(dms2[3])/60+parseFloat(dms2[4].replace(',','.'))/3600,lon=parseInt(dms2[6])+parseInt(dms2[7])/60+parseFloat(dms2[8].replace(',','.'))/3600;if(/[Ss]/.test(dms2[1]))lat=-lat;if(/[Ww]/.test(dms2[5]))lon=-lon;if(Math.abs(lat)<=90&&Math.abs(lon)<=180)return{lat,lon,_src:'WGS-84 ГМС'};}

  // ГМ: 55°45.360'N 37°37.040'E
  const ddm=t.match(/(\d{1,3})[°\s]+(\d{1,2}(?:[.,]\d+)?)[''\s]+([NSns])\s+(\d{1,3})[°\s]+(\d{1,2}(?:[.,]\d+)?)[''\s]+([EWew])/);
  if(ddm){let lat=parseInt(ddm[1])+parseFloat(ddm[2].replace(',','.'))/60,lon=parseInt(ddm[4])+parseFloat(ddm[5].replace(',','.'))/60;if(/[Ss]/.test(ddm[3]))lat=-lat;if(/[Ww]/.test(ddm[6]))lon=-lon;if(Math.abs(lat)<=90&&Math.abs(lon)<=180)return{lat,lon,_src:'WGS-84 ГМ'};}
  const ddm2=t.match(/([NSns])\s*(\d{1,3})[°\s]+(\d{1,2}(?:[.,]\d+)?)[''\s]*\s+([EWew])\s*(\d{1,3})[°\s]+(\d{1,2}(?:[.,]\d+)?)[''\s]*/);
  if(ddm2){let lat=parseInt(ddm2[2])+parseFloat(ddm2[3].replace(',','.'))/60,lon=parseInt(ddm2[5])+parseFloat(ddm2[6].replace(',','.'))/60;if(/[Ss]/.test(ddm2[1]))lat=-lat;if(/[Ww]/.test(ddm2[4]))lon=-lon;if(Math.abs(lat)<=90&&Math.abs(lon)<=180)return{lat,lon,_src:'WGS-84 ГМ'};}

  // ГГ с буквами: N 55.7558 E 37.6173
  const dd_dir=t.match(/([NSns])\s*(\d{1,3}(?:[.,]\d+)?)[°,\s]+([EWew])\s*(\d{1,3}(?:[.,]\d+)?)/);
  if(dd_dir){let lat=parseFloat(dd_dir[2].replace(',','.')),lon=parseFloat(dd_dir[4].replace(',','.'));if(/[Ss]/.test(dd_dir[1]))lat=-lat;if(/[Ww]/.test(dd_dir[3]))lon=-lon;if(Math.abs(lat)<=90&&Math.abs(lon)<=180)return{lat,lon,_src:'WGS-84 ГГ'};}

  // ГГ: 55.7558, 37.6173
  const dd=t.match(/^(-?\d{1,3}(?:[.,]\d+)?)[,;\s]+(-?\d{1,3}(?:[.,]\d+)?)$/);
  if(dd){const a=parseFloat(dd[1].replace(',','.')),b=parseFloat(dd[2].replace(',','.'));if(Math.abs(a)<=90&&Math.abs(b)<=180)return{lat:a,lon:b,_src:'WGS-84 ГГ'};if(Math.abs(b)<=90&&Math.abs(a)<=180)return{lat:b,lon:a,_src:'WGS-84 ГГ'};}

  return null;
}

