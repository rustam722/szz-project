const _GH32='0123456789bcdefghjkmnpqrstuvwxyz';
function _toGeohash(lat,lon,prec=9){
  let minLa=-90,maxLa=90,minLo=-180,maxLo=180,hash='',even=true;
  while(hash.length<prec){let idx=0;for(let bit=4;bit>=0;bit--){let mid;if(even){mid=(minLo+maxLo)/2;if(lon>=mid){idx|=(1<<bit);minLo=mid;}else maxLo=mid;}else{mid=(minLa+maxLa)/2;if(lat>=mid){idx|=(1<<bit);minLa=mid;}else maxLa=mid;}even=!even;}hash+=_GH32[idx];}
  return hash;
}
function _fromGeohash(hash){
  let minLa=-90,maxLa=90,minLo=-180,maxLo=180,even=true;
  for(const ch of hash.toLowerCase()){const idx=_GH32.indexOf(ch);if(idx<0)return null;for(let bit=4;bit>=0;bit--){const set=idx&(1<<bit);if(even){const mid=(minLo+maxLo)/2;if(set)minLo=mid;else maxLo=mid;}else{const mid=(minLa+maxLa)/2;if(set)minLa=mid;else maxLa=mid;}even=!even;}}
  return{lat:(minLa+maxLa)/2,lon:(minLo+maxLo)/2};
}

