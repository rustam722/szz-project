const _MGRS_COL='ABCDEFGHJKLMNPQRSTUVWXYZ';
const _MGRS_ROW='ABCDEFGHJKLMNPQRSTUV';
function _toMGRS(lat_d, lon_d) {
  const utm=_utmForward(lat_d,lon_d);
  const {zone,band,easting,northing}=utm;
  const colSet=((zone-1)%3)*8;
  const colIdx=Math.floor(easting/100000)-1;
  if(colIdx<0||colIdx>7) return null;
  const rowOffset=zone%2===0?5:0;
  const rowIdx=(Math.floor(northing/100000)+rowOffset)%20;
  const eStr=String(Math.floor(easting)%100000).padStart(5,'0');
  const nStr=String(Math.floor(northing)%100000).padStart(5,'0');
  return `${zone}${band} ${_MGRS_COL[colSet+colIdx]}${_MGRS_ROW[rowIdx]} ${eStr} ${nStr}`;
}

