// Возвращает массив подходящих систем (WGS-84 + название)
// ──────────────────────────────────────────────
function _tryMSK(X, Y) {
  const candidates = [];
  for (const sys of MSK_DB) {
    try {
      // Грубая проверка: northing от экватора должен быть разумным
      const Xn = X - sys.fn;
      if (Xn < 3500000 || Xn > 9500000) continue;
      const sk42 = _gkInvAt(X, Y, sys.lon0, sys.fe, sys.fn, _EL.KRASS);
      if (!sk42) continue;
      const wgs = _sk42ToWgs(sk42.lat, sk42.lon);
      // Должно быть в пределах РФ
      if (wgs.lat < 41 || wgs.lat > 82 || wgs.lon < 19 || wgs.lon > 192) continue;
      // Должно быть в ожидаемом регионе системы
      if (sys.latr && (wgs.lat < sys.latr[0] || wgs.lat > sys.latr[1])) continue;
      if (sys.lonr && (wgs.lon < sys.lonr[0] || wgs.lon > sys.lonr[1])) continue;
      candidates.push({ lat: wgs.lat, lon: wgs.lon, _src: sys.name, _sysId: sys.id, _sys: sys });
    } catch(e) {}
  }
  return candidates;
}

function _mskById(id, X, Y) {
  const sys = MSK_DB.find(s => s.id === id);
  if (!sys) return null;
  const sk42 = _gkInvAt(X, Y, sys.lon0, sys.fe, sys.fn, _EL.KRASS);
  if (!sk42) return null;
  const wgs = _sk42ToWgs(sk42.lat, sk42.lon);
  return { lat: wgs.lat, lon: wgs.lon, _src: sys.name, _sysId: sys.id, _sys: sys };
}

