const _UTMBANDS = 'CDEFGHJKLMNPQRSTUVWX';

function _utmForward(lat_d, lon_d) {
  const el=_EL.WGS84, e2=_e2(el), k0=0.9996;
  const zone=Math.floor((lon_d+180)/6)+1;
  const lon0=(zone-1)*6-180+3;
  const res=_gkFwdAt(lat_d, lon_d, lon0, 500000, 0, el);
  // Scale factor k0 — упрощённо используем _gkFwdAt без k0, корректируем вручную
  // (для точного UTM используем полную формулу)
  const lat=lat_d*Math.PI/180, dL=(lon_d-lon0)*Math.PI/180;
  const sinL=Math.sin(lat), cosL=Math.cos(lat);
  const N=el.a/Math.sqrt(1-e2*sinL**2);
  const ep2=(e2/(1-e2))*cosL**2;
  const A=cosL*dL, t=Math.tan(lat);
  const M=_meridianArc(lat, el);
  const E=k0*N*(A+(1-t**2+ep2)*A**3/6+(5-18*t**2+t**4+72*ep2-58*(e2/(1-e2)))*A**5/120)+500000;
  let Nr=k0*(M+N*Math.tan(lat)*(A**2/2+(5-t**2+9*ep2+4*ep2**2)*A**4/24+(61-58*t**2+t**4+600*ep2-330*(e2/(1-e2)))*A**6/720));
  if(lat_d<0) Nr+=10000000;
  const bandIdx=Math.min(Math.max(Math.floor((lat_d+80)/8),0),19);
  const band=(lat_d>=-80&&lat_d<=84)?_UTMBANDS[bandIdx]:'';
  return {zone,band,easting:Math.round(E*10)/10,northing:Math.round(Nr*10)/10};
}

function _utmInverse(zone, band, easting, northing) {
  const el=_EL.WGS84, e2=_e2(el), k0=0.9996;
  const e1=(1-Math.sqrt(1-e2))/(1+Math.sqrt(1-e2));
  const e12=e1**2, e13=e1**3, e14=e1**4;
  const x=easting-500000;
  let y=northing;
  if(band&&'CDEFGHJKLM'.includes(band.toUpperCase())) y-=10000000;
  const mu=y/k0/(el.a*(1-e2/4-3*e2**2/64-5*e2**3/256));
  const latFP=mu+(3*e1/2-27*e13/32)*Math.sin(2*mu)+(21*e12/16-55*e14/32)*Math.sin(4*mu)+(151*e13/96)*Math.sin(6*mu)+(1097*e14/512)*Math.sin(8*mu);
  const sinFP=Math.sin(latFP),cosFP=Math.cos(latFP);
  const N=el.a/Math.sqrt(1-e2*sinFP**2);
  const R=el.a*(1-e2)/(1-e2*sinFP**2)**1.5;
  const ep2=(e2/(1-e2))*cosFP**2;
  const D=x/(N*k0), t=Math.tan(latFP);
  const lat=latFP-(N*t/R)*(D**2/2-(5+3*t**2+10*ep2-4*ep2**2-9*(e2/(1-e2)))*D**4/24+(61+90*t**2+298*ep2+45*t**4-252*(e2/(1-e2))-3*ep2**2)*D**6/720);
  const lon=(zone-1)*6-180+3+(D-(1+2*t**2+ep2)*D**3/6+(5-2*ep2+28*t**2-3*ep2**2+8*(e2/(1-e2))+24*t**4)*D**5/120)/cosFP*180/Math.PI;
  const lat_d=lat*180/Math.PI;
  if(Math.abs(lat_d)>90) return null;
  return {lat:lat_d,lon};
}

